export type AffiliateDetail = {
  hasPassword: boolean;
  payoutDetails: string | null;
  commissions: AffiliateDetailCommission[];
};

/**
 * What the detail sheet shows that the list row does not.
 *
 * Fetched for the whole page up front rather than on click, so opening a row
 * is instant and needs no loading state. Bounded by `perAffiliate`, so the
 * cost is a page of rows times a handful of commissions, not an affiliate's
 * entire history.
 */
export async function getAffiliateDetails(
  ownerId: string,
  merchantId: string,
  affiliateIds: string[],
  perAffiliate = 8,
): Promise<Record<string, AffiliateDetail>> {
  await assertMerchantOwnership(ownerId, merchantId);
  if (affiliateIds.length === 0) return {};

  const affiliates = await db.affiliate.findMany({
    where: { id: { in: affiliateIds }, merchantId, merchant: { ownerId } },
    select: {
      id: true,
      payoutDetails: true,
      passwordHash: true,
      commissions: {
        select: {
          id: true,
          amount: true,
          currency: true,
          status: true,
          createdAt: true,
        },
        orderBy: { createdAt: "desc" },
        take: perAffiliate,
      },
    },
  });

  return Object.fromEntries(
    affiliates.map((a) => [
      a.id,
      {
        payoutDetails: a.payoutDetails,
        hasPassword: a.passwordHash !== null,
        commissions: a.commissions.map((c) => ({
          id: c.id,
          amount: c.amount.toFixed(2),
          currency: c.currency,
          status: c.status as CommissionStatus,
          createdAt: c.createdAt,
        })),
      },
    ]),
  );
}

/**
 * How many referred subscribers there are, and how many are still paying. A
 * referral confirmed as a self referral earns nothing more, so it is not
 * counted as still paying.
 */
export async function referralCounts(
  affiliateId: string,
): Promise<{ total: number; active: number }> {
  const [total, active] = await Promise.all([
    db.click.count({
      where: {
        affiliateId,
        commissions: { some: {} },
        referredSubscriptions: { some: {} },
      },
    }),
    db.click.count({
      where: {
        affiliateId,
        commissions: { some: {} },
        referredSubscriptions: { some: {} },
        subscriptionCancelledAt: null,
        fraudConfirmedAt: null,
      },
    }),
  ]);
  return { total, active };
}
