// Owner-scoping is done in the query, never inferred from the route guard.
// An Affiliate reaches an Owner only through its Merchant, so both links get
// checked: the Merchant is the Owner's, and the Affiliate is that Merchant's.
async function assertMerchantOwnership(
  ownerId: string,
  merchantId: string,
): Promise<void> {
  const merchant = await db.merchant.findFirst({
    where: { id: merchantId, ownerId },
    select: { id: true },
  });
  if (!merchant) {
    throw new Error("Merchant not found");
  }
}

export type CreateAffiliateInput = {
  name: string;
  email: string;
  /**
   * An explicit code the affiliate chose for themselves, e.g. on the signup
   * form's live link preview. Skips `generateLinkCode`: a name-derived
   * suggestion is free to retry itself into a different code on collision,
   * a code someone typed on purpose is not — the caller decides what a
   * collision on this means instead.
   */
  code?: string;
  /** Argon2id hash of the password chosen at signup. */
  passwordHash?: string;
};

function normalizeEmail(email: string): string {
  return email.trim().toLowerCase();
}

// Callers are expected to have already established that the Owner owns this
// Merchant (the dashboard reaches this only via listMerchantsForOwner), so
// this takes no ownerId and does no ownership check of its own.
export async function countAffiliatesForMerchant(
  merchantId: string,
): Promise<number> {
  return db.affiliate.count({ where: { merchantId } });
}

export async function createAffiliate(
  merchantId: string,
  programId: string,
  input: CreateAffiliateInput,
): Promise<{ id: string; email: string; referralCode: string }> {
  const email = normalizeEmail(input.email);
  const code = input.code ?? (await generateLinkCode(input.name, merchantId));

  // One transaction: the code is unique within its Merchant and generated by a
  // read-then-write, so a losing race must not leave an Affiliate with no link.
  // The code lock makes the retired check and the insert one step against a
  // concurrent rename or delete that is retiring the same code.
  const affiliate = await db.$transaction(async (tx) => {
    await lockLinkCodes(tx, merchantId, [code]);
    if (await isLinkCodeTaken(tx, merchantId, code)) {
      // Raised as the same unique violation a live code produces, so every
      // caller's existing "code taken" handling covers a retired code as well.
      throw new Prisma.PrismaClientKnownRequestError("That code is retired.", {
        code: "P2002",
        clientVersion: Prisma.prismaVersion.client,
        meta: { target: ["code"] },
      });
    }
    return tx.affiliate.create({
      data: {
        merchantId,
        programId,
        email,
        name: input.name,
        passwordHash: input.passwordHash,
        links: { create: { code, isPrimary: true } },
      },
      select: { id: true, email: true },
    });
  });

  return { id: affiliate.id, email: affiliate.email, referralCode: code };
}

export async function getAffiliateByEmail(
  merchantId: string,
  email: string,
): Promise<{ id: string; email: string; referralCode: string } | null> {
  const affiliate = await db.affiliate.findUnique({
    where: { merchantId_email: { merchantId, email: normalizeEmail(email) } },
    select: {
      id: true,
      email: true,
      links: { where: { isPrimary: true }, select: { code: true } },
    },
  });
  if (!affiliate) return null;
  return {
    id: affiliate.id,
    email: affiliate.email,
    referralCode: affiliate.links[0]?.code ?? "",
  };
}

